/**
 * Expand 2-digit NAICS sectors to all 5-6 digit codes within those sectors
 * 
 * @param sectors - Array of 2-digit NAICS sector codes (e.g., ["33", "48", "62"])
 * @returns Array of all 5-6 digit NAICS codes within those sectors
 */
export function expandNaicsSectors(sectors: string[]): string[] {
  const expanded: string[] = [];
  
  for (const sector of sectors) {
    const codes = NAICS_CODES_BY_SECTOR[sector];
    if (codes) {
      expanded.push(...codes);
    } else {
      console.warn(`[NAICS Expansion] No codes found for sector ${sector}`);
    }
  }
  
  return expanded;
}

/**
 * Get all unique 2-digit sectors from a list of NAICS codes
 * 
 * @param codes - Array of NAICS codes (any length)
 * @returns Array of unique 2-digit sector codes
 */
export function extractSectors(codes: string[]): string[] {
  const sectors = new Set<string>();
  for (const code of codes) {
    if (code.length >= 2) {
      sectors.add(code.substring(0, 2));
    }
  }
  return Array.from(sectors).sort();
}

/**
 * Get count of codes available for a sector
 */
export function getSectorCodeCount(sector: string): number {
  return NAICS_CODES_BY_SECTOR[sector]?.length || 0;
}

/**
 * Get all available sectors
 */
export function getAllSectors(): string[] {
  return Object.keys(NAICS_CODES_BY_SECTOR).sort();
}
